const BUNDLES: Record<Locale, Record<string, string>> = {
  en,
  tr,
  de,
  es,
  fr,
  ja,
  ko,
  'zh-Hans': zhHans,
  ar,
  'pt-BR': ptBr,
  ru,
};

/**
 * Looks up a localized string for a key in the given locale, falling back to
 * English and finally to the key itself.
 */
export function translate(key: string, locale: Locale = 'en'): string {
  const bundle = BUNDLES[locale];
  const value = bundle?.[key];
  if (value !== undefined) return value;
  const fallback = en[key as keyof typeof en];
  return fallback !== undefined ? fallback : key;
}

/** Returns the localized display name for a muscle. */
export function muscleDisplayName(
  muscle: string,
  locale: Locale = 'en'
): string {
  return translate(`muscle.${muscle}`, locale);
}

/** Returns the localized display name for a muscle side. */
export function sideDisplayName(side: string, locale: Locale = 'en'): string {
  return translate(`side.${side}`, locale);
}

/** Returns the localized display name for a body side (front/back). */
export function bodySideDisplayName(side: string, locale: Locale = 'en'): string {
  return translate(`bodySide.${side}`, locale);
}

/** Returns the localized display name for a body gender. */
export function genderDisplayName(gender: string, locale: Locale = 'en'): string {
  return translate(`gender.${gender}`, locale);
}
