export type Locale =
  | 'en'
  | 'tr'
  | 'de'
  | 'es'
  | 'fr'
  | 'ja'
  | 'ko'
  | 'zh-Hans'
  | 'ar'
  | 'pt-BR'
  | 'ru';

export const LOCALES: readonly Locale[] = [
  'en',
  'tr',
  'de',
  'es',
  'fr',
  'ja',
  'ko',
  'zh-Hans',
  'ar',
  'pt-BR',
  'ru',
];

/** Maps a BCP-47-style language tag to a supported locale (best effort). */
export function normalizeLocale(tag: string): Locale {
  const lower = tag.toLowerCase();
  const normalized = lower.replace('_', '-');
  if (normalized === 'zh-hans' || normalized === 'zh-cn' || normalized === 'zh') {
    return 'zh-Hans';
  }
  if (normalized === 'pt-br') return 'pt-BR';
  if (normalized === 'pt' || normalized === 'pt-pt') return 'pt-BR';
  if ((LOCALES as readonly string[]).includes(normalized)) {
    return normalized as Locale;
  }
  if (normalized.startsWith('en')) return 'en';
  if (normalized.startsWith('tr')) return 'tr';
  if (normalized.startsWith('de')) return 'de';
  if (normalized.startsWith('es')) return 'es';
  if (normalized.startsWith('fr')) return 'fr';
  if (normalized.startsWith('ja')) return 'ja';
  if (normalized.startsWith('ko')) return 'ko';
  if (normalized.startsWith('ar')) return 'ar';
  if (normalized.startsWith('ru')) return 'ru';
  return 'en';
}

/** The current locale, detected from `navigator.language` or the browser setting. */
export function currentLocale(): Locale {
  if (typeof navigator !== 'undefined' && navigator.language) {
    return normalizeLocale(navigator.language);
  }
  return 'en';
}

